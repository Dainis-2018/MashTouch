# PlatformIO pre-build script: gzips web/index.html into
# src/net/webui_data.h, so the web UI is part of the firmware (and is
# updated with it over the air). The header is only rewritten when the
# page changes, so unchanged builds stay incremental.
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

root = env.subst("$PROJECT_DIR")  # noqa: F821
src = os.path.join(root, "web", "index.html")
dst = os.path.join(root, "src", "net", "webui_data.h")

with open(src, "rb") as f:
    page = f.read()
data = gzip.compress(page, compresslevel=9, mtime=0)

lines = []
for i in range(0, len(data), 20):
    lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")
text = (
    "// Generated by tools/embed_web.py from web/index.html - do not edit.\n"
    "// SPDX-License-Identifier: GPL-3.0-or-later\n"
    "#pragma once\n"
    "#include <stddef.h>\n"
    "#include <stdint.h>\n\n"
    "static const uint8_t kWebUi[] = {\n" + "\n".join(lines) + "\n};\n"
    "static const size_t kWebUiLen = sizeof(kWebUi);\n"
)

old = None
if os.path.exists(dst):
    with open(dst, "r", encoding="utf-8") as f:
        old = f.read()
if old != text:
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("embed_web: web/index.html %d bytes -> %d bytes gzipped" % (len(page), len(data)))
